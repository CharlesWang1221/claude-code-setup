#!/bin/bash
# 把 Claude Code 目前的 skills 跟本地 MCP servers 同步到 Codex CLI。
# 用法：./tools/sync-codex.sh
set -euo pipefail

CLAUDE_SKILLS="$HOME/.claude/skills"
CODEX_SKILLS="$HOME/.codex/skills"
MANIFEST="$CODEX_SKILLS/.claude-sync-manifest"
CLAUDE_JSON="$HOME/.claude.json"
CODEX_CONFIG="$HOME/.codex/config.toml"

# Codex 已內建同款 skill，不用重複同步
SKIP_SKILLS=("skill-creator")

GREEN='\033[0;32m'
GRAY='\033[0;90m'
NC='\033[0m'

echo "=== 同步 Skills（Claude → Codex）==="
mkdir -p "$CODEX_SKILLS"
touch "$MANIFEST"

# 先移除「上次同步過、但 Claude 那邊已經刪掉」的 skill
if [[ -s "$MANIFEST" ]]; then
    while IFS= read -r name; do
        [[ -z "$name" ]] && continue
        if [[ ! -d "$CLAUDE_SKILLS/$name" ]]; then
            echo -e "${GRAY}  移除已刪除的 skill: $name${NC}"
            rm -rf "$CODEX_SKILLS/$name"
        fi
    done < "$MANIFEST"
fi

: > "$MANIFEST"
if [[ -d "$CLAUDE_SKILLS" ]]; then
    for dir in "$CLAUDE_SKILLS"/*/; do
        [[ -d "$dir" ]] || continue
        name=$(basename "$dir")
        [[ "$name" == ".git" ]] && continue

        skip=false
        for s in "${SKIP_SKILLS[@]}"; do
            [[ "$name" == "$s" ]] && skip=true
        done
        if $skip; then
            echo -e "${GRAY}  跳過（Codex 內建）: $name${NC}"
            continue
        fi

        rm -rf "$CODEX_SKILLS/$name"
        cp -R "$dir" "$CODEX_SKILLS/$name"
        echo "$name" >> "$MANIFEST"
        echo -e "${GREEN}  已同步: $name${NC}"
    done
else
    echo -e "${GRAY}  找不到 $CLAUDE_SKILLS，跳過${NC}"
fi

echo ""
echo "=== 同步 MCP servers（Claude → Codex）==="

if [[ ! -f "$CLAUDE_JSON" ]]; then
    echo -e "${GRAY}  找不到 $CLAUDE_JSON，跳過（先跑過 Claude Code 加好 MCP 再重跑）${NC}"
    exit 0
fi

python3 - "$CLAUDE_JSON" "$CODEX_CONFIG" <<'PYEOF'
import json
import re
import sys

claude_json_path, codex_config_path = sys.argv[1], sys.argv[2]

with open(claude_json_path) as f:
    claude = json.load(f)
servers = claude.get("mcpServers", {})

def toml_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

BEGIN = "# >>> claude-code-sync: MCP servers (auto-generated by tools/sync-codex.sh, do not edit by hand) >>>"
END = "# <<< claude-code-sync: MCP servers <<<"

lines = [BEGIN]
for name, cfg in servers.items():
    lines.append(f"[mcp_servers.{name}]")
    lines.append(f"command = {toml_str(cfg.get('command', ''))}")
    args = cfg.get("args", [])
    lines.append("args = [" + ", ".join(toml_str(a) for a in args) + "]")
    env = cfg.get("env") or {}
    lines.append("")
    if env:
        lines.append(f"[mcp_servers.{name}.env]")
        for k, v in env.items():
            lines.append(f"{k} = {toml_str(v)}")
        lines.append("")
lines.append(END)
block = "\n".join(lines).rstrip() + "\n"

import os
os.makedirs(os.path.dirname(codex_config_path), exist_ok=True)
if os.path.exists(codex_config_path):
    with open(codex_config_path) as f:
        content = f.read()
else:
    content = ""

pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.DOTALL)
if pattern.search(content):
    content = pattern.sub(block, content)
else:
    if not content.endswith("\n"):
        content += "\n"
    content = content + "\n" + block

with open(codex_config_path, "w") as f:
    f.write(content)

print(f"  已寫入 {len(servers)} 個 MCP server 到 {codex_config_path}")
for name in servers:
    print(f"    - {name}")
PYEOF

echo ""
echo "=== 完成，驗證中 ==="
codex mcp list 2>&1 | awk 'NR==1 || /filesystem|playwright|cloudflare|firecrawl|google-workspace|plaud/'
